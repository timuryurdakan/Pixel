#!/usr/bin/env python3
"""Build the connector zipapp (V3.md §2, §5.4): web/connector/pixel-connector.pyz + web/connector/SHA256SUMS.

    python3 tools/build_connector.py            # build and write
    python3 tools/build_connector.py --check    # exit 1 if the committed files differ from a fresh build

Only git-tracked files under pixel_connector/ are bundled (`git ls-files`; without git, all of them with a warning).
The archive is reproducible: entries sorted, fixed timestamps (1980-01-01), fixed modes, stored (no compression, so
the bytes don't depend on the local zlib). Contents: pixel_connector/**.py, pixel_agent.py (from web/hook/, used for
office presence), a root __main__.py and a generated pixel_connector/_build.py with the build id (v2.md E1): the first
12 hex digits of a SHA-256 over the bundled source names and contents. It depends only on the sources (not on git), so
`--check` stays reproducible; `pixel-connector --version`, `doctor`, `/ctl/status` and `device.info` report it.
Stdlib only, Python ≥ 3.8 at run time.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "web" / "connector"
PYZ = "pixel-connector.pyz"
SUMS = "SHA256SUMS"
BUILD_MODULE = "pixel_connector/_build.py"
BUILD_ID_LEN = 12
SHEBANG = b"#!/usr/bin/env python3\n"
MAIN = b'''"""pixel-connector zipapp entry point."""
import sys

if sys.version_info < (3, 8):
    sys.stderr.write("pixel-connector: Python 3.8 or newer is required\\n")
    raise SystemExit(2)

from pixel_connector.__main__ import main

raise SystemExit(main())
'''


def package_paths(root: Path = ROOT, run=subprocess.run) -> list:
    """The pixel_connector/**.py files to bundle: only git-tracked ones (v2.md D8), so a stray untracked module
    never ends up in the .pyz. Without git (or outside a checkout) every .py under the package, with a warning."""
    try:
        r = run(["git", "ls-files", "-z", "--", "pixel_connector"], cwd=str(root), capture_output=True, timeout=30)
        if r.returncode != 0:
            raise OSError((r.stderr or b"").decode("utf-8", "replace").strip() or "git ls-files failed")
        names = [n for n in r.stdout.decode("utf-8").split("\0") if n.endswith(".py")]
        paths = [root / n for n in names if (root / n).is_file()]
    except (OSError, subprocess.SubprocessError) as e:
        print("build_connector: warning: git unavailable (%s); bundling every .py under pixel_connector/" % e,
              file=sys.stderr)
        paths = list((root / "pixel_connector").rglob("*.py"))
    return sorted(p for p in paths if "__pycache__" not in p.parts and p.relative_to(root).as_posix() != BUILD_MODULE)


def sources(root: Path = ROOT, run=subprocess.run) -> list:
    files = [(p.relative_to(root).as_posix(), p.read_bytes()) for p in package_paths(root, run)]
    files.append(("pixel_agent.py", (root / "web" / "hook" / "pixel_agent.py").read_bytes()))
    files.append(("__main__.py", MAIN))
    return sorted(files)


def build_id(files=None) -> str:
    """Short SHA-256 over every bundled file (name, length, bytes), so renaming or moving content changes it too."""
    h = hashlib.sha256()
    for name, data in (files if files is not None else sources()):
        h.update(name.encode("utf-8") + b"\0" + str(len(data)).encode("ascii") + b"\0")
        h.update(data)
    return h.hexdigest()[:BUILD_ID_LEN]


def build_module(bid: str) -> bytes:
    return ('"""Generated by tools/build_connector.py; not in the source tree."""\nBUILD = "%s"\n' % bid).encode("ascii")


def build_bytes() -> bytes:
    files = sources()
    files = sorted(files + [(BUILD_MODULE, build_module(build_id(files)))])
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_STORED) as z:
        for name, data in files:
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.external_attr = 0o644 << 16
            info.create_system = 3
            z.writestr(info, data)
    return SHEBANG + buf.getvalue()


def sums_text(files: dict) -> str:
    return "".join("%s  %s\n" % (hashlib.sha256(data).hexdigest(), name) for name, data in sorted(files.items()))


def outputs() -> dict:
    pyz = build_bytes()
    files = {PYZ: pyz}
    for name in ("install.sh", "install.ps1"):
        files[name] = (OUT_DIR / name).read_bytes()
    return {PYZ: pyz, SUMS: sums_text(files).encode("ascii")}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="verify the committed files instead of writing them")
    args = p.parse_args(argv)
    out = outputs()
    if args.check:
        bad = [n for n, data in out.items() if not (OUT_DIR / n).exists() or (OUT_DIR / n).read_bytes() != data]
        if bad:
            print("out of date: %s (run python3 tools/build_connector.py)" % ", ".join(bad), file=sys.stderr)
            return 1
        print("web/connector is up to date")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, data in out.items():
        (OUT_DIR / name).write_bytes(data)
    digest = hashlib.sha256(out[PYZ]).hexdigest()
    print("wrote web/connector/%s (%d bytes, sha256 %s, build %s) and %s" % (PYZ, len(out[PYZ]), digest, build_id(),
                                                                           SUMS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
